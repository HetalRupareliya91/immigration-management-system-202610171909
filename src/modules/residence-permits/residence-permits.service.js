'use strict';

const { ResidencePermitsRepository } = require('./residence-permits.repository');
const { validateResidencePermits } = require('./residence-permits.validator');

function httpError(status, message, details) {
  const err = new Error(message);
  err.status = status;
  if (details) err.details = details;
  return err;
}

class ResidencePermitsService {
  constructor(repository = new ResidencePermitsRepository()) {
    this.repository = repository;
  }

  list(filters = {}) {
    return this.repository.findAll(filters);
  }

  get(id) {
    const item = this.repository.findById(id);
    if (!item) throw httpError(404, 'residence-permits record not found');
    return item;
  }

  create(payload) {
    const errors = validateResidencePermits(payload);
    if (errors.length) throw httpError(400, 'Validation failed', errors);
    return this.repository.create(payload);
  }

  update(id, payload) {
    this.get(id);
    const errors = validateResidencePermits(payload, { partial: true });
    if (errors.length) throw httpError(400, 'Validation failed', errors);
    return this.repository.update(id, payload);
  }

  remove(id) {
    this.get(id);
    this.repository.remove(id);
  }
}

module.exports = { ResidencePermitsService };